class QuestionMistakeDetail(BaseModel):
    """Detailed question response sent by Quiz Agent or Frontend."""

    question_id: str = Field(..., description="Unique question identifier")
    topic: str = Field(..., description="Topic or concept tag for the question")
    difficulty: Literal["easy", "medium", "hard"] = Field(
        default="medium", description="Difficulty level"
    )
    cognitive_level: Literal["recall", "understanding", "application", "analysis"] = (
        Field(default="understanding", description="Bloom's taxonomy cognitive level")
    )
    question_text: str = Field(..., description="Question statement")
    selected_answer: str = Field(..., description="Student's chosen answer")
    correct_answer: str = Field(..., description="Ground-truth correct answer")
    is_correct: bool = Field(..., description="Whether student answered correctly")
    explanation: str = Field(
        default="", description="Pedagogical explanation of the solution"
    )

    @field_validator("topic", "question_text", "selected_answer", "correct_answer")
    @classmethod
    def strip_and_validate(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Field cannot be empty or whitespace only.")
        return cleaned


class QuizSubmissionRequest(BaseModel):
    """Validated input payload for quiz analysis submitted to Recommendation Agent."""

    student_id: str = Field(..., min_length=1, max_length=100, description="Student ID")
    document_id: str = Field(..., min_length=1, description="Associated document ID")
    quiz_id: str = Field(default="generic_quiz", description="Quiz ID")
    quiz_title: str = Field(
        default="Course Assessment", description="Title of the quiz"
    )
    time_spent_seconds: int = Field(
        default=0, ge=0, description="Total duration in seconds"
    )
    questions: list[QuestionMistakeDetail] = Field(
        ..., min_length=1, description="List of questions and answers"
    )

    @field_validator("student_id", "document_id", "quiz_id", "quiz_title")
    @classmethod
    def clean_strings(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("String field cannot be empty.")
        return cleaned


class TopicMastery(BaseModel):
    """Calculated mastery metrics for a single topic."""

    topic: str
    total_questions: int
    correct_count: int
    accuracy_percentage: float
    mastery_status: Literal["Mastered", "Review Needed", "Critical Gap"]
    weighted_severity_score: float
    difficulty_breakdown: dict[str, dict[str, int]]


class KnowledgeGap(BaseModel):
    """Identified concept gap with transparent explainability reasoning."""

    gap_id: str
    topic: str
    severity: Literal["CRITICAL", "MODERATE", "MINOR"]
    confidence_score: float = Field(
        ..., ge=0.0, le=1.0, description="Confidence in gap diagnosis"
    )
    explanation: str = Field(
        ..., description="Clear human-readable justification of the gap"
    )
    missed_questions_count: int
    sample_misconceptions: list[str]
    suggested_prerequisites: list[str] = Field(default_factory=list)


class StudyActionItem(BaseModel):
    """Prioritized actionable study step for the student."""

    priority: int = Field(..., ge=1, description="1 is highest priority")
    topic: str
    action_type: Literal["Review Lecture", "Practice Drills", "Deep Conceptual Review"]
    title: str
    description: str
    estimated_minutes: int
    lecture_citations: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Relevant document chunks and page numbers",
    )


class TutorHandoffPackage(BaseModel):
    """Ready-to-consume structured payload for the Tutor Agent."""

    recommendation_id: str
    student_id: str
    document_id: str
    target_topics: list[str]
    gap_severity: Literal["CRITICAL", "MODERATE", "MINOR", "NONE"]
    pedagogical_instruction: str
    suggested_opening_prompt: str
    relevant_lecture_chunks: list[dict[str, Any]] = Field(default_factory=list)


class RecommendationResponse(BaseModel):
    """Comprehensive explainable recommendation response."""

    recommendation_id: str
    attempt_id: str
    student_id: str
    document_id: str
    created_at: str
    overall_score: int
    total_questions: int
    score_percentage: float
    mastery_level: str
    summary: str
    topic_mastery: list[TopicMastery]
