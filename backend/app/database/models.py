from dataclasses import asdict, dataclass
import json
from typing import Any, Literal
from pydantic import BaseModel, Field, field_validator


@dataclass(frozen=True)
class DocumentRecord:
    """Metadata kept for one successfully indexed PDF."""

    document_id: str
    original_filename: str
    stored_filename: str
    page_count: int
    pages_with_text: int
    chunk_count: int
    file_size_bytes: int
    created_at: str

    def to_public_dict(self) -> dict[str, str | int]:
        """Return only fields that are safe for API clients to see."""
        public_record = asdict(self)
        public_record.pop("stored_filename")
        return public_record


@dataclass(frozen=True)
class QuizAttemptRecord:
    """Persisted record of a student's quiz attempt."""

    attempt_id: str
    student_id: str
    document_id: str
    quiz_id: str
    quiz_title: str
    total_questions: int
    score: int
    time_spent_seconds: int
    submission_data_json: str
    created_at: str

    def to_dict(self) -> dict[str, Any]:
        """Return the record with parsed submission data."""
        data = asdict(self)
        try:
            data["submission_data"] = json.loads(self.submission_data_json)
        except Exception:
            data["submission_data"] = []
        return data


@dataclass(frozen=True)
class RecommendationRecord:
    """Persisted recommendation analysis generated by the Recommendation Agent."""

    recommendation_id: str
    attempt_id: str
    student_id: str
    document_id: str
    overall_score_percentage: float
    mastery_level: str
    summary: str
    topic_mastery_json: str
    knowledge_gaps_json: str
    action_items_json: str
    tutor_handoff_json: str
    created_at: str

    def to_dict(self) -> dict[str, Any]:
        """Return the recommendation record with parsed JSON structures."""
        record_dict = asdict(self)
        for json_key, target_key in [
            ("topic_mastery_json", "topic_mastery"),
            ("knowledge_gaps_json", "knowledge_gaps"),
            ("action_items_json", "action_items"),
            ("tutor_handoff_json", "tutor_handoff"),
        ]:
            try:
                record_dict[target_key] = json.loads(record_dict[json_key])
            except Exception:
                record_dict[target_key] = []
        return record_dict


