class QuizEvaluationResponse(BaseModel):
    """Complete grading report with score breakdown and recommendation bridge."""

    quiz_id: str
    attempt_id: str
    student_id: str
    document_id: str
    quiz_title: str
    total_questions: int
    score: float
    max_possible_score: float
